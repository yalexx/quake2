function seedOf(text) {
  let h = 2166136261;
  for (const c of Buffer.from(text)) h = Math.imul(h ^ c, 16777619) >>> 0;
  return h;
}

// Deterministic binary noise that starts with NUL, 0xff and invalid UTF-8, so
// any text decoding or newline handling on the way would show.
function noise(seed, length) {
  const out = Buffer.alloc(length);
  let x = Math.imul(seed, 2654435761) >>> 0 || 1;
  for (let i = 0; i < length; i++) {
    x ^= x << 13; x >>>= 0;
    x ^= x >>> 17;
    x ^= x << 5; x >>>= 0;
    out[i] = x & 0xff;
  }
  out.set([0x00, 0xff, 0xfe, 0x0d, 0x0a, 0xc3, 0x28, 0x1a].slice(0, length));
  return out;
}

// The four files the engine writes for one save slot.
function saveFiles(slot, version) {
  return Object.entries(SLOT_FILES).map(([name, size]) => {
    const rel = `baseq2/save/${slot}/${name}`;
    return [rel, noise(seedOf(rel + "#" + version), size + version * 17)];
  });
}

// ---- HTTP ------------------------------------------------------------------

// One request on its own connection, path sent verbatim. `stream(req, done)`
// writes the body itself; keepAlive lets the server answer an upload early
// and keep reading, instead of closing on the rest of it.
function request(method, urlPath, { body, headers = {}, stream, keepAlive = false, timeout = 60000 } = {}) {
  return new Promise((resolve, reject) => {
    const sent = { Origin: "null", ...headers }; // what the opaque-origin page sends
    if (body !== undefined) sent["Content-Length"] = String(body.length);
    if (keepAlive) sent.Connection = "keep-alive";
    let req;
    try {
      req = http.request({ host: "127.0.0.1", port, method, path: urlPath, headers: sent, agent: false });
    } catch (err) {
      reject(new Error(`${method} ${urlPath}: ${err.message}`));
      return;
    }
    let settled = false;
    const timer = setTimeout(() => settle(new Error("no response within " + timeout + " ms")), timeout);
    function settle(err, value) {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      if (err || stream || keepAlive) req.destroy();
      if (err) reject(new Error(`${method} ${urlPath}: ${err.message}`));
      else resolve(value);
    }
    req.on("response", (res) => {
      const chunks = [];
      res.on("data", (chunk) => chunks.push(chunk));
      res.on("end", () => {
        responses.push({ method, path: urlPath, status: res.statusCode, acao: res.headers["access-control-allow-origin"] });
        settle(null, { status: res.statusCode, headers: res.headers, body: Buffer.concat(chunks), sent: req.getHeaders() });
      });
      res.on("error", settle);
    });
    req.on("error", settle); // once answered (an upload cut short by a 413), ignored
    if (stream) stream(req, () => settled).catch(settle);
    else req.end(body);
  });
}

function drained(req) {
  return new Promise((resolve) => {
    const done = () => {
      req.off("drain", done);
      req.off("close", done);
      resolve();
    };
    req.on("drain", done);
    req.on("close", done);
  });
}

function expectedListing() {
  return [...expected].map(([rel, data]) => ({ path: rel, size: data.length })).sort(byPath);
}

async function listing(prefix) {
  const r = await request("GET", prefix);
  assert.strictEqual(r.status, 200, `GET ${prefix} status`);
  assert.match(String(r.headers["content-type"]), /^application\/json/, `GET ${prefix} Content-Type`);
  const json = JSON.parse(r.body.toString("utf8"));
  assert.ok(json && Array.isArray(json.files), `GET ${prefix} has no "files" array`);
  return json.files.slice().sort(byPath);
}

async function assertListing(prefix) {
  assert.deepStrictEqual(await listing(prefix), expectedListing(), `GET ${prefix} lists other paths or sizes than were stored`);
}

async function assertFile(prefix, rel, data) {
  const r = await request("GET", prefix + rel);
  assert.strictEqual(r.status, 200, `GET ${prefix}${rel} status`);
  assert.ok(r.body.equals(data), `GET ${prefix}${rel} returned ${r.body.length} bytes that differ from the ${data.length} stored`);
}

async function post(prefix, rel, data, headers) {
  const r = await request("POST", prefix + rel, { body: data, headers });
  assert.strictEqual(r.status, 204, `POST ${prefix}${rel} status (${r.body.toString("utf8").trim()})`);
  assert.strictEqual(r.body.length, 0, `POST ${prefix}${rel} 204 carries a body`);
  return r;
}

// Sends each [method, path, status, body?] and returns the ones answered otherwise.
async function statusMismatches(cases) {
  const wrong = [];
  for (const [method, urlPath, want, body] of cases) {
    const r = await request(method, urlPath, body === undefined ? {} : { body });
    if (r.status !== want) wrong.push(`${method} ${urlPath} -> ${r.status}, want ${want}`);
  }
  return wrong;
}

// ---- Disk ------------------------------------------------------------------

// Every entry under dir, sorted, folders ending in "/", dot files included.
function walk(dir, prefix = "", out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      out.push(prefix + entry.name + "/");
      walk(path.join(dir, entry.name), prefix + entry.name + "/", out);
    } else {
      out.push(prefix + entry.name);
    }
  }
  return out.sort();
}

// What walk(dataDir) must show: the stored files and the folders above them.
function expectedDisk() {
  const out = new Set();
  for (const rel of expected.keys()) {
    const parts = rel.split("/");
    for (let i = 1; i < parts.length; i++) out.add(parts.slice(0, i).join("/") + "/");
    out.add(rel);
  }
  return [...out].sort();
}

function assertDisk() {
  const leftovers = walk(dataDir).filter((rel) => /(^|\/)\.[^/]*\/?$|\.tmp$/.test(rel));
  assert.deepStrictEqual(leftovers, [], "temp or dot files left in the data dir");
  assert.deepStrictEqual(walk(dataDir), expectedDisk(), "the data dir on disk holds other files or folders than were stored");
  for (const [rel, data] of expected) {
    assert.ok(fs.readFileSync(path.join(dataDir, ...rel.split("/"))).equals(data), `${rel} on disk differs from what was stored`);
  }
}

// Names, sizes and mtimes (never contents) of everything under dir.
function snapshot(dir) {
  let st;
  try {
    st = fs.lstatSync(dir);
  } catch (err) {
    if (err.code === "ENOENT") return ["(absent)"];
    throw err;
  }
  const out = [`./ size=${st.size} mtime=${st.mtimeMs}`];
  if (st.isDirectory()) {
    for (const rel of walk(dir)) {
      const s = fs.lstatSync(path.join(dir, rel));
      out.push(`${rel} size=${s.size} mtime=${s.mtimeMs}`);
    }
  }
  return out;
}

// ---- The server under test -------------------------------------------------

function portIsFree(p) {
  return new Promise((resolve) => {
    const probe = http.createServer();
    probe.once("error", () => resolve(0));
    probe.listen(p, "127.0.0.1", () => {
      const got = probe.address().port;
      probe.close(() => resolve(got));
    });
  });
}

async function pickPort() {
  if (await portIsFree(PREFERRED_PORT)) return PREFERRED_PORT;
  for (let i = 0; i < 20; i++) {
    const p = await portIsFree(0);
    if (p && p !== LIVE_PORT) return p;
  }
  throw new Error("found no free port");
}

// Resolves once the child prints its listening line; rejects if it exits first.
function spawnServer(p) {
  return new Promise((resolve, reject) => {
    if (p === LIVE_PORT) throw new Error("refusing the live service's port " + LIVE_PORT);
    const proc = spawn(process.execPath, [SERVER], {
      cwd: ROOT,
      env: { ...process.env, PORT: String(p), QUAKE2_DATA_DIR: dataDir },
      stdio: ["ignore", "pipe", "pipe"],
    });
    child = proc;
    let out = "";
    let err = "";
    const ready = `http://127.0.0.1:${p}/`;
    const timer = setTimeout(() => fail("did not start listening within 10 s"), 10000);
    function fail(why) {
      clearTimeout(timer);
      proc.kill("SIGKILL");
      reject(Object.assign(new Error(`server.js on port ${p} ${why}: ${(out + err).trim()}`), {
        addrInUse: err.includes("EADDRINUSE"),
        output: out,
      }));
    }
    proc.stdout.on("data", (chunk) => {
      out += chunk;
      serverLog += chunk;
      if (out.includes(ready)) {
        clearTimeout(timer);
        resolve(() => out);
      }
    });
    proc.stderr.on("data", (chunk) => {
      err += chunk;
      serverLog += chunk;
    });
    proc.once("error", (e) => fail(e.message));
    proc.once("close", (code, signal) => fail(`exited (${signal || code}) before listening`));
  });
}

// Another run can take the port between the probe and the child's listen:
// then pick again. What the losing attempts printed (their startup cleanup
// ran before the listen failed) stays part of childOut().
async function launch() {
  let earlier = "";
  for (let attempt = 1; ; attempt++) {
    const p = await pickPort();
    try {
      const out = await spawnServer(p);
      childOut = () => earlier + out();
      port = p;
      return;
    } catch (err) {
      if (!err.addrInUse || attempt === 5) throw err;
      earlier += err.output;
    }
  }
}

// Stops the child this script started, and nothing else.
function stopServer() {
  const proc = child;
  if (!proc || proc.exitCode !== null || proc.signalCode !== null) return Promise.resolve();
  return new Promise((resolve) => {
    const force = setTimeout(() => proc.kill("SIGKILL"), 5000);
    proc.once("exit", () => {
      clearTimeout(force);
      resolve();
    });
    proc.kill("SIGTERM");
  });
}

// Where an escape attempt lands on a server that lets it through, outside the
// temp folders: only files this run wrote (its TOKEN name, PWNED bytes).
function escapedFiles() {
  return [os.tmpdir(), ROOT, path.dirname(ROOT)].map((dir) => path.join(dir, TOKEN)).filter((file) => {
    try {
      return fs.lstatSync(file).isFile() && fs.readFileSync(file).equals(PWNED);
    } catch {
      return false;
    }
  });
}

function cleanupSync() {
  if (child && child.exitCode === null && child.signalCode === null) child.kill("SIGKILL");
  for (const dir of [dataDir, outsideDir]) if (dir) fs.rmSync(dir, { recursive: true, force: true });
  for (const file of escapedFiles()) fs.rmSync(file, { force: true });
}

