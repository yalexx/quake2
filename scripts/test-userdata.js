// Ways out of the data dir to `name` in outsideDir (its sibling), each with
// the status server.js must answer.
function escapes(name) {
  const out = path.basename(outsideDir);
  const abs = path.join(outsideDir, name).split(path.sep).slice(1).map(encodeURIComponent);
  return [
    // The URL parser resolves these dot segments (and takes "\" for "/")
    // before server.js sees the path, which then lands on the static route
    // with no such file in the app folder: 404, never the store.
    [`../${out}/${name}`, 404],
    [`%2e%2e/${out}/${name}`, 404],
    [`%2E%2E/${out}/${name}`, 404],
    [`.%2e/${out}/${name}`, 404],
    [`./../${out}/${name}`, 404],
    [`baseq2/../../${out}/${name}`, 404],
    [`..\\${out}\\${name}`, 404],
    // Encoded separators, backslashes and absolute paths reach the store: 403.
    [`..%2f${out}%2f${name}`, 403],
    [`%2e%2e%2f${out}%2f${name}`, 403],
    [`.%2e%2f${out}%2f${name}`, 403],
    [`baseq2%2f..%2f..%2f${out}%2f${name}`, 403],
    [`baseq2/%2e%2e%2f%2e%2e%2f${out}/${name}`, 403],
    [`..%5c${out}%5c${name}`, 403],
    [`baseq2%5c..%5c..%5c${out}%5c${name}`, 403],
    [`..%2f${out}%2f${name}%00`, 403],
    ["%2f" + abs.join("%2f"), 403],
    ["/" + abs.join("/"), 403],
  ];
}

