async function check(name, fn) {
  try {
    await fn();
    results.push(true);
    console.log("PASS  " + name);
  } catch (err) {
    results.push(false);
    console.log("FAIL  " + name + "\n        " + String((err && err.message) || err).replace(/\n/g, "\n        "));
  }
}

async function main() {
  const before = snapshot(REAL_USERDATA);
  dataDir = fs.mkdtempSync(path.join(os.tmpdir(), "q2-userdata-"));
  outsideDir = fs.mkdtempSync(path.join(os.tmpdir(), "q2-userdata-outside-"));
  fs.writeFileSync(path.join(outsideDir, "secret.txt"), SECRET);

  let started = false;
  await check("server.js starts on a free port other than 4231 with QUAKE2_DATA_DIR set to a temp dir", async () => {
    await launch();
    assert.notStrictEqual(port, LIVE_PORT);
    assert.ok(childOut().includes("saves in " + dataDir), "the startup line names another data dir: " + childOut().trim());
    started = true;
  });
  if (started) {
    console.log(`      server.js pid ${child.pid} on 127.0.0.1:${port}, data dir ${dataDir}`);
    for (const [name, fn] of CHECKS) await check(name, fn);
  } else {
    console.log(`SKIP  the other ${CHECKS.length} checks: no server to run them against`);
  }
  await stopServer();

  await check("the repo's userdata/ is unchanged (names, sizes, mtimes)", async () => {
    assert.deepStrictEqual(snapshot(REAL_USERDATA), before, REAL_USERDATA + " changed during the test");
  });
  await check("the server was stopped and the temp folders removed", async () => {
    cleanupSync();
    assert.ok(child === null || child.exitCode !== null || child.signalCode !== null, "server.js is still running");
    for (const dir of [dataDir, outsideDir]) assert.ok(!fs.existsSync(dir), dir + " is still there");
  });

  const failed = results.filter((ok) => !ok).length;
  const total = results.length + (started ? 0 : CHECKS.length);
  if (failed || !started) {
    const tail = serverLog.trim().split("\n").slice(-25).join("\n        ");
    if (tail) console.log("\nserver.js output (last lines):\n        " + tail);
  }
  console.log(`\n${total - failed - (started ? 0 : CHECKS.length)}/${total} checks passed`);
  process.exitCode = failed || !started ? 1 : 0;
}

process.on("exit", cleanupSync);
for (const signal of ["SIGINT", "SIGTERM", "SIGHUP"]) {
  process.on(signal, () => {
    console.log(`\nInterrupted (${signal}): stopping server.js and removing the temp folders`);
    process.exit(130);
  });
}
