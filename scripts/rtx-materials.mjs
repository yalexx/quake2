// Build the small upload-fingerprint catalog; never alters either PAK.
import fs from 'node:fs';
import { readPakDirectory, decodePng, readWal, globalPalette } from './texture-lib.mjs';
import { materialFor } from './material-classes.mjs';
const root = new URL('../', import.meta.url);
const pak = fs.readFileSync(new URL('baseq2/pak0.pak', root));
const hires = fs.readFileSync(new URL('baseq2/pak9.pak', root));
const { palette } = globalPalette(pak);
const catalog = {};
function add(width, height, rgba, name, material) {
  let hash = 2166136261;
  for (let i = 0; i < 64; i++) {
    const p = Math.floor(i * (width * height - 1) / 63) * 4;
    for (let c = 0; c < 3; c++) hash = Math.imul(hash ^ rgba[p + c], 16777619);
  }
  const key = `${width}x${height}:${hash >>> 0}`;
  const value = [name, material];
  if (catalog[key] && catalog[key][1] !== material) throw new Error('Ambiguous material ' + name);
  catalog[key] = value;
}
const entries = readPakDirectory(pak);
for (const [name, entry] of entries) {
  if (!name.endsWith('.wal')) continue;
  const bytes = pak.subarray(entry.offset, entry.offset + entry.length);
  const wal = readWal(bytes);
  const material = materialFor({ name, flags: wal.flags, contents: wal.contents }).material;
  const rgba = Buffer.alloc(wal.width * wal.height * 4, 255);
  const start = bytes.readUInt32LE(40);
  for (let p = 0; p < wal.width * wal.height; p++) for (let c = 0; c < 3; c++) rgba[p * 4 + c] = palette[bytes[start + p] * 3 + c];
  add(wal.width, wal.height, rgba, name, material);
}
for (const [name, entry] of readPakDirectory(hires)) {
  if (!name.startsWith('textures/') || !name.endsWith('.png')) continue;
  const picture = decodePng(hires.subarray(entry.offset, entry.offset + entry.length));
  const walName = name.replace(/\.png$/, '.wal');
  add(picture.width, picture.height, picture.data, walName, materialFor({ name: walName }).material);
}
const output = '// Generated by node scripts/rtx-materials.mjs; reviewed material classes, sampled RGB upload identities.\nwindow.quake2MaterialCatalog = ' + JSON.stringify(catalog) + ';\n';
const dest = new URL('rtx-materials.js', root);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(dest, 'utf8') !== output) throw new Error('Material catalog is stale');
} else fs.writeFileSync(dest, output);
console.log('RTX material catalog: ' + Object.keys(catalog).length + ' texture identities; PAKs unchanged.');
